//! The closed lists of characters of a confirmation (ruling RD-90 items 2, 7 and 8), at Unicode
//! 13.0.0. Everything from the doc line of `NO_FORM` to the end of this file is the output of the
//! program `GENERATOR` of tests/items_native_card.rs, run as `/usr/bin/python3 -I -c <GENERATOR>`
//! with Python's unicodedata 13.0.0; the test `the_character_tables_are_those_of_unicodedata_13`
//! makes them again and compares. A code point that 13.0.0 does not assign is in the category Cn
//! and so in `NO_FORM`: a character newer than the tables never counts as one that can be seen.

/// The version of Unicode whose tables these lists are.
pub const UNICODE_VERSION: (u8, u8, u8) = (13, 0, 0);

/// The most marks of the general category M (`combining`) that may follow one another in a
/// deciding value and on a line of a native card, a mark with no character before it counted
/// as well (ruling RD-131 item 1). Three is the longest stack in the localized strings of
/// macOS (42,267 files): Devanagari, Arabic, Kannada and Gurmukhi take three; Thai, Hebrew,
/// Tamil, Bengali, Khmer and Lao two; Latin, Greek and Cyrillic one.
pub const MOST_MARKS: usize = 3;

/// The variation selectors, which change the form of the character before them and have none.
const SELECTORS: &[(u32, u32)] = &[(0x180B, 0x180D), (0xFE00, 0xFE0F), (0xE0100, 0xE01EF)];

/// The characters whose category gives them a form that they do not show: the combining grapheme
/// joiner, the Hangul fillers, the Khmer inherent vowels and the blank Braille pattern.
const SHOW_NONE: &[(u32, u32)] = &[
    (0x034F, 0x034F),
    (0x115F, 0x1160),
    (0x17B4, 0x17B5),
    (0x2800, 0x2800),
    (0x3164, 0x3164),
    (0xFFA0, 0xFFA0),
];

fn within(table: &[(u32, u32)], c: char) -> bool {
    let c = u32::from(c);
    table
        .binary_search_by(|&(lo, hi)| {
            if hi < c {
                std::cmp::Ordering::Less
            } else if lo > c {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// Whether `c` has no visible form (ruling RD-90 item 7): a control character, a format
/// character (the joiners and the direction marks among them, item 8), a line or paragraph
/// separator, a private use or unassigned code point, a variation selector, or a character of
/// `SHOW_NONE`.
pub fn no_form(c: char) -> bool {
    within(NO_FORM, c) || within(SELECTORS, c) || within(SHOW_NONE, c)
}

/// Whether `c` is a blank: a code point of the category Zs.
pub fn blank(c: char) -> bool {
    within(BLANKS, c)
}

/// Whether `c` is a mark drawn on the character before it: the categories Mn and Me.
pub fn mark(c: char) -> bool {
    within(MARKS, c)
}

/// Whether `c` is a mark of the general category M: Mn, Mc or Me.
pub fn combining(c: char) -> bool {
    mark(c) || within(SPACING_MARKS, c)
}

/// The marks of `c`'s canonical decomposition and whether a character that is no mark starts it;
/// none for a character that decomposes to no mark.
fn decomposed(c: char) -> Option<(usize, bool)> {
    let c = u32::from(c);
    DECOMPOSED
        .binary_search_by(|&(lo, hi, _, _)| {
            if hi < c {
                std::cmp::Ordering::Less
            } else if lo > c {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .ok()
        .map(|i| (usize::from(DECOMPOSED[i].2), DECOMPOSED[i].3))
}

/// The longest run of marks of the general category M in the canonical decomposition (NFD) of
/// `text`, so that a precomposed letter counts the marks that it carries (ruling RD-137 M1), and
/// whether a mark stands with no base before it: at the start, after a blank or after a
/// character with no visible form (ruling RD-137 M2).
fn mark_scan(text: &str) -> (usize, bool) {
    let mut run = 0;
    let mut most = 0;
    let mut orphan = false;
    let mut before: Option<char> = None;
    for c in text.chars() {
        let marks = match decomposed(c) {
            Some((k, true)) => {
                run = 0;
                k
            }
            Some((k, false)) => k,
            None if combining(c) => 1,
            None => {
                run = 0;
                0
            }
        };
        let starts_with_mark = marks > 0 && decomposed(c).is_none_or(|(_, base)| !base);
        if starts_with_mark && run == 0 && before.is_none_or(|b| blank(b) || no_form(b)) {
            orphan = true;
        }
        run += marks;
        most = most.max(run);
        before = Some(c);
    }
    (most, orphan)
}

/// The longest run of marks of the general category M in `text`, counted on its canonical
/// decomposition, a run at its start or after a blank counted as well.
pub fn marks_in_a_row(text: &str) -> usize {
    mark_scan(text).0
}

/// Whether a mark of `text` has no base before it: at its start, after a blank or after a
/// character with no visible form.
pub fn orphan_mark(text: &str) -> bool {
    mark_scan(text).1
}

/// The columns that `text` takes on a line: none for a `mark`, two for a character whose East
/// Asian width is W or F, and one for every other character. A bound in columns counts display
/// width and not characters, so that 120 wide characters take 240 columns and a letter with a
/// combining mark takes one.
pub fn columns(text: &str) -> usize {
    text.chars()
        .map(|c| {
            if mark(c) {
                0
            } else if within(WIDE, c) {
                2
            } else {
                1
            }
        })
        .sum()
}

/// Whether `value` equals its own composed form (ruling RD-90 item 2) at the bound of `most`
/// columns: at least one character, no character with no visible form, no blank at its start or
/// end and no two blanks in a row, no mark with no base before it (`orphan_mark`), no more than
/// `MOST_MARKS` marks in a row on its canonical decomposition (`marks_in_a_row`), and at most
/// `most` columns.
pub fn composed(value: &str, most: usize) -> bool {
    let chars: Vec<char> = value.chars().collect();
    if chars.is_empty() {
        return false;
    }
    for (i, &c) in chars.iter().enumerate() {
        let edge = i == 0 || i + 1 == chars.len();
        if no_form(c) || (blank(c) && (edge || blank(chars[i + 1]))) {
            return false;
        }
    }
    let (marks, orphan) = mark_scan(value);
    !orphan && marks <= MOST_MARKS && columns(value) <= most
}

